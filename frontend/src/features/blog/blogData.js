export const getPostBySlug = (slug) => BLOG_POSTS.find((post) => post.slug === slug);

export const getRelatedPosts = (post) => {
  if (!post) return [];
  const related = (post.content.relatedSlugs || [])
    .map((slug) => getPostBySlug(slug))
    .filter(Boolean);

  if (related.length > 0) return related;

  return BLOG_POSTS.filter((p) => p.slug !== post.slug).slice(0, 3);
};
